print("test_loader",len(test_loader))

class_names = train_data.classes

label2id = {label: id for id, label in enumerate(class_names)}
id2label = {id: label for id, label in enumerate(class_names)}

model = AutoModelForImageClassification.from_pretrained(
    model_name,
    num_labels=len(class_names),
    label2id=label2id,
    id2label=id2label,
    ignore_mismatched_sizes=True,
)
model = model.to(device)
model.config.label2id = label2id
model.config.id2label = id2label

print(class_names)
print(label2id)
print(id2label)

criterion = torch.nn.CrossEntropyLoss()

optimizer = torch.optim.Adam(model.parameters(), lr=0.00002)
epochs = 5
train_losses= []
train_accuracies = []

for epoch in range(epochs):
    model.train()
    total_loss = 0
    correct_predictions = 0
    total_images = 0

    for images, labels in train_loader:
        images = images.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()
        outputs = model(pixel_values=images)

        loss = criterion(outputs.logits, labels)
        loss.backward()
        optimizer.step()

        total_loss += loss.item()
        images_size = images.size(0)
        total_images += images_size

        predictions = outputs.logits.argmax(dim=1)

        correct_predictions += (predictions == labels).sum().item()

    average_loss = total_loss / len(train_loader)
    Training_accuracy  = 100 * correct_predictions / total_images

    train_losses.append(average_loss)
    train_accuracies.append(Training_accuracy )


    print(f"Epoch {epoch+1}/{epochs}")
    print(f"Train Accuracy: {Training_accuracy:.4f}%")
    print(f"Average Loss: {average_loss:.4f}")

