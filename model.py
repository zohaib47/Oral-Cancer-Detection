import os
import shutil
import hashlib
from pathlib import Path
from collections import Counter

import kagglehub
from sklearn.model_selection import train_test_split
from torchvision import datasets

SEED = 42

# ----- 1. Download + dono versions ke paths -----
root_path = Path(kagglehub.dataset_download("zaidpy/oral-cancer-dataset"))
print("root_path:", root_path)

SOURCES = {
    "v1": root_path / "Oral Cancer" / "Oral Cancer Dataset",
    "v2": root_path / "Oral cancer Dataset 2.0" / "OC Dataset kaggle new",
}
CLASS_FOLDERS = {"CANCER": "CANCER", "NON_CANCER": "NON CANCER"}  # new name -> original folder

for s, p in SOURCES.items():
    assert p.exists(), f"{s} folder nahi mila: {p}"

# ----- 2. Sari images collect (hash ke saath) -----
def md5(p):
    return hashlib.md5(p.read_bytes()).hexdigest()

records = []  # (path, label, source, hash)
for src, src_path in SOURCES.items():
    for cls, folder in CLASS_FOLDERS.items():
        for p in sorted((src_path / folder).glob("*")):
            if p.suffix.lower() in {".jpg", ".jpeg", ".png"}:
                records.append((p, cls, src, md5(p)))

print("\nRaw images:", len(records))
print("Per source/class:", dict(Counter((r[2], r[1]) for r in records)))

labels_by_hash = {}
for _, cls, _, h in records:
    labels_by_hash.setdefault(h, set()).add(cls)
conflict_hashes = {h for h, c in labels_by_hash.items() if len(c) > 1}
print("Label conflicts (same image CANCER + NON_CANCER):", len(conflict_hashes))


files, labels, srcs, seen = [], [], [], set()
dropped = Counter()
for p, cls, src, h in records:
    if h in conflict_hashes:
        dropped["conflict"] += 1
        continue
    if h in seen:
        dropped[f"duplicate_from_{src}"] += 1
        continue
    seen.add(h)
    files.append(p)
    labels.append(cls)
    srcs.append(src)

print("Dropped:", dict(dropped))
print("\nUnique images:", len(files), {c: labels.count(c) for c in CLASS_FOLDERS})
print("Unique per source:", dict(Counter(srcs)))


tr_f, tmp_f, tr_l, tmp_l, tr_s, tmp_s = train_test_split(
    files, labels, srcs, test_size=0.30, stratify=labels, random_state=SEED)
va_f, te_f, va_l, te_l, va_s, te_s = train_test_split(
    tmp_f, tmp_l, tmp_s, test_size=0.50, stratify=tmp_l, random_state=SEED)


dataset_path = "/content/oral_dataset"
if os.path.exists(dataset_path):
    shutil.rmtree(dataset_path)

for split, fs, ls, ss in [("train", tr_f, tr_l, tr_s),
                          ("val", va_f, va_l, va_s),
                          ("test", te_f, te_l, te_s)]:
    for f, l, s in zip(fs, ls, ss):
        out = Path(dataset_path) / split / l
        out.mkdir(parents=True, exist_ok=True)
        shutil.copy2(f, out / f"{s}_{f.name}")


train_path = os.path.join(dataset_path, "train")
val_path = os.path.join(dataset_path, "val")
test_path = os.path.join(dataset_path, "test")

